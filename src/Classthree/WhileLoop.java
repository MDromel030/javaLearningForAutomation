package Classthree;

public class WhileLoop {
    public static void main(String[] args) {

        // While loop
        System.out.println("While loop:");
        int i = 1;
        while (i <= 5) {
            System.out.println(i);
            i++;
        }

        // Do-while loop
        System.out.println("Do-while loop:");
        int j = 1;
        do {
            System.out.println(j);
            j++;
        } while (j <= 5);
    }
}
