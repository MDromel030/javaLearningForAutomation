package git_3;

public class WhileLoopStatement {

    public static void main(String[] args) {

        // while loop
        System.out.println("While Loop:");

        int i = 1;

        while (i <= 5) {
            System.out.println(i);
            i++;
        }

        // do-while loop
        System.out.println("\nDo While Loop:");

        int j = 1;

        do {
            System.out.println(j);
            j++;
        } while (j <= 5);
    }
}

